#!/usr/bin/env python3
"""Fit a variance head on all given runs and export it as integer weights for the engine.

The engine computes
    risk = (sum_i W[i] * x[i] + B) >> Shift
(with --shared, one set of weights for all buckets; otherwise W and B are per bucket)
where x are the 128 inputs of the final layer (0..127), and risk is the head's prediction
standardised over the training data (mean 0) in units of 1/RiskOne standard deviations.
"""

import argparse

import numpy as np

import analyze as A
import variance_head as V

SHIFT = 12
RISK_ONE = 64  # risk units per standard deviation


def write_shared(a, n, w, c):
    rows = [", ".join(f"{int(x):5d}" for x in w[i:i + 16]) for i in range(0, len(w), 16)]
    body = ",\n  ".join(rows)
    with open(a.out, "w") as f:
        f.write(f"""// Generated by research/export_head.py --shared (target '{a.target}', {n} positions).
// A linear output on the inputs of the final NNUE layer, fitted to how far the static eval
// overestimates the position (log scale). Standardised: {RISK_ONE} is one standard deviation.
// It is specific to the default net and has to be refitted when the net changes.

#ifndef NNUE_RISK_WEIGHTS_H_INCLUDED
#define NNUE_RISK_WEIGHTS_H_INCLUDED

#include "../types.h"

namespace Stockfish::Eval::NNUE {{

constexpr int RiskShift = {SHIFT};
constexpr i32 RiskBias  = {int(c)};

// clang-format off
constexpr i16 RiskWeights[{len(w)}] = {{
  {body}}};
// clang-format on

}}  // namespace Stockfish::Eval::NNUE

#endif  // #ifndef NNUE_RISK_WEIGHTS_H_INCLUDED
""")
    print(f"wrote {a.out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("files", nargs="+")
    ap.add_argument("--acts", required=True)
    ap.add_argument("--target", choices=list(V.TARGETS), default="down")
    ap.add_argument("--out", required=True, help="C++ header to write")
    ap.add_argument("--min-bucket", type=int, default=1000)
    ap.add_argument("--shared", action="store_true", help="one set of weights for all buckets")
    a = ap.parse_args()

    acts = np.load(a.acts)
    df = A.add_features(A.load(a.files, 1000))
    df, X, b = V.attach(df, acts)
    y = V.TARGETS[a.target](df.err_static.values)
    if a.shared:
        a.min_bucket = 10 ** 9
    cv, lp, lb = V.choose_lams(X, b, y, df.book_idx.values, min_bucket=a.min_bucket)
    h = V.VarianceHead(lp, lb, a.min_bucket).fit(X, b, y)
    pred = h.predict(X, b)
    m, s = pred.mean(), pred.std()
    print(f"target {a.target}: n={len(y)}, CV R^2 {cv:.3f}, lambdas {lp:g}/{lb:g}, pred mean {m:.3f} sd {s:.3f}")

    # Fold standardisation and bucket corrections into per-bucket weights on the raw activations
    W = np.zeros((32, X.shape[1]))
    C = np.zeros(32)
    for k in range(32):
        w = h.w0.copy()
        c = h.b0
        if k in h.per:
            c += h.per[k][0]
            w += h.per[k][1]
        W[k] = w / h.sd
        C[k] = c - (h.mu / h.sd) @ w
    scale = RISK_ONE / s * (1 << SHIFT)
    Wq = np.round(W * scale).astype(np.int64)
    Cq = np.round((C - m) * scale).astype(np.int64)
    assert np.abs(Wq).max() < 2 ** 15, "weights overflow int16"

    # Check: integer pipeline against the float model
    risk_float = (pred - m) / s * RISK_ONE
    risk_int = ((X.astype(np.int64) * Wq[b]).sum(1) + Cq[b]) >> SHIFT
    err = risk_int - risk_float
    print(f"max |W| {np.abs(Wq).max()}, quantisation error in risk units: mean {err.mean():.3f}, "
          f"max abs {np.abs(err).max():.3f} (1 sd = {RISK_ONE})")
    print("risk percentiles 1/10/50/90/99:", np.percentile(risk_int, [1, 10, 50, 90, 99]).round().tolist())

    if a.shared:
        write_shared(a, len(y), Wq[0], Cq[0])
        return

    with open(a.out, "w") as f:
        f.write(f"""// Generated by research/export_head.py (target '{a.target}', {len(y)} positions).
// Linear head on the inputs of the final NNUE layer that predicts how far the static eval
// overestimates the position (log scale), standardised: {RISK_ONE} = one standard deviation.

#ifndef NNUE_RISK_WEIGHTS_H_INCLUDED
#define NNUE_RISK_WEIGHTS_H_INCLUDED

#include "../types.h"

namespace Stockfish::Eval::NNUE {{

constexpr int RiskShift = {SHIFT};

// clang-format off
constexpr i32 RiskBias[32] = {{{", ".join(str(int(c)) for c in Cq)}}};

constexpr i16 RiskWeights[32][{X.shape[1]}] = {{
""")
        for k in range(32):
            f.write("  {" + ", ".join(str(int(w)) for w in Wq[k]) + "},\n")
        f.write("""};
// clang-format on

}  // namespace Stockfish::Eval::NNUE

#endif  // #ifndef NNUE_RISK_WEIGHTS_H_INCLUDED
""")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
